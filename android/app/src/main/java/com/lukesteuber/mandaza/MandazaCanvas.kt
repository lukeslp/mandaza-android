package com.lukesteuber.mandaza

import androidx.compose.foundation.Canvas
import androidx.compose.runtime.Composable
import androidx.compose.runtime.LaunchedEffect
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableFloatStateOf
import androidx.compose.runtime.produceState
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.runtime.withFrameNanos
import androidx.compose.ui.Modifier
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.Path
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.drawscope.Stroke
import androidx.compose.ui.graphics.graphicsLayer
import androidx.compose.ui.unit.dp
import com.lukesteuber.mandaza.core.EngineConfig
import com.lukesteuber.mandaza.core.GeneratedMandaza
import com.lukesteuber.mandaza.core.MandazaEngine
import com.lukesteuber.mandaza.core.MandazaPalettes
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.isActive
import kotlinx.coroutines.withContext
import kotlin.math.sin

@Composable
fun MandazaCanvas(
    seed: String,
    paletteId: String,
    config: EngineConfig,
    canvasWidth: Float,
    canvasHeight: Float,
    tilt: Offset,
    parallaxAmount: Float,
    audioLevel: Float,
    reactivity: Float,
    paperTheme: Boolean,
    modifier: Modifier = Modifier,
) {
    val generated by produceState<GeneratedMandaza?>(
        initialValue = null,
        seed, config, canvasWidth, canvasHeight,
    ) {
        if (canvasWidth > 1 && canvasHeight > 1) {
            value = withContext(Dispatchers.Default) {
                MandazaEngine(config).generate(canvasWidth.toDouble(), canvasHeight.toDouble(), seed)
            }
        }
    }
    var elapsed by remember(generated) { mutableFloatStateOf(0f) }
    LaunchedEffect(generated, config.drawSpeed) {
        var previous = 0L
        while (isActive) {
            withFrameNanos { now ->
                if (previous != 0L) elapsed += (now - previous) / 1_000_000_000f *
                    (0.35f + config.drawSpeed.toFloat() * 1.9f) * (1f + audioLevel * reactivity * 1.5f)
                previous = now
            }
        }
    }
    val throb = 1f + audioLevel * reactivity * 0.22f
    val ground = if (paperTheme) Color(0xFFF1E6CF) else Color(0xFF05060A)
    val palette = remember(paletteId) { MandazaPalettes.byId(paletteId) }

    Canvas(
        modifier = modifier.graphicsLayer { scaleX = throb; scaleY = throb },
    ) {
        drawRect(ground)
        val art = generated ?: return@Canvas
        val totalCurves = art.loops.sumOf { it.curves.size }.coerceAtLeast(1)
        val visible = (elapsed * totalCurves / 4f).toInt().coerceAtMost(totalCurves)
        var consumed = 0
        val baseWidth = (art.radius / 30 * config.lineWidth).toFloat().coerceAtLeast(1f)
        art.loops.forEach { loop ->
            val count = (visible - consumed).coerceIn(0, loop.curves.size)
            consumed += loop.curves.size
            if (count <= 0) return@forEach
            var colorPosition = if (loop.colorTotal > 1) loop.colorIndex.toDouble() / (loop.colorTotal - 1) else 0.5
            if (config.idlePulse) colorPosition += 0.18 * sin(elapsed / 2.5 + loop.colorIndex * 0.6)
            if (colorPosition < 0) colorPosition = -colorPosition
            if (colorPosition > 1) colorPosition = 2 - colorPosition
            val color = Color(palette.colorAt(colorPosition).toInt())
            val depth = if (loop.colorTotal > 1) loop.colorIndex.toFloat() / (loop.colorTotal - 1) else 0.5f
            // Normal handheld tilt is only a fraction of gravity. Give it enough
            // physical travel to read clearly while preserving per-layer depth.
            val travel = parallaxAmount * 180.dp.toPx() * (0.25f + depth * 0.75f)
            val shift = Offset(tilt.x * travel, tilt.y * travel)
            val path = Path()
            loop.curves.take(count).forEachIndexed { index, curve ->
                if (index == 0) path.moveTo(curve.start.x.toFloat() + shift.x, curve.start.y.toFloat() + shift.y)
                path.cubicTo(
                    curve.control1.x.toFloat() + shift.x, curve.control1.y.toFloat() + shift.y,
                    curve.control2.x.toFloat() + shift.x, curve.control2.y.toFloat() + shift.y,
                    curve.end.x.toFloat() + shift.x, curve.end.y.toFloat() + shift.y,
                )
            }
            if (config.glow) {
                drawPath(
                    path,
                    color.copy(alpha = 0.16f + 0.22f * config.glowStrength.toFloat()),
                    style = Stroke(
                        width = baseWidth * (3f + config.glowStrength.toFloat() * 3f),
                        cap = StrokeCap.Round,
                        join = StrokeJoin.Round,
                    ),
                )
            }
            drawPath(
                path,
                if (paperTheme) color.copy(alpha = 0.86f) else color,
                style = Stroke(width = baseWidth, cap = StrokeCap.Round, join = StrokeJoin.Round),
            )
        }
    }
}
